"""Writes the list of the Check Mission rules in its user guide, from the rule catalogue (the single source of the texts).

Catalogue: GDC AR Mission Maker Tools/scripts/WorkbenchGame/GDC/MissionCheck/GDC_MMMissionCheckCatalog.c
User guide: GDC AR Mission Maker Tools/docs/GDC_CheckMission.md and .fr.md, between the RULES markers. A rule with a
knowledge base sheet links to it.

    python rules_doc.py           update both guides
    python rules_doc.py --check   only check that they are up to date (exit 1 if not)
"""
import argparse
import re
import sys
from pathlib import Path

ADDON = Path(__file__).resolve().parents[2] / "GDC_AR_Misc" / "GDC AR Mission Maker Tools"
CATALOGUE = ADDON / "scripts" / "WorkbenchGame" / "GDC" / "MissionCheck" / "GDC_MMMissionCheckCatalog.c"
GUIDES = {"en": ADDON / "docs" / "GDC_CheckMission.md", "fr": ADDON / "docs" / "GDC_CheckMission.fr.md"}
KB_LINK = "../GDC_AR_MissionCheck_KB/"
START = "<!-- RULES:START (generated by Tools/MissionCheckKB/rules_doc.py from the rule catalogue: do not edit) -->"
END = "<!-- RULES:END -->"
STRING = r'"((?:[^"\\]|\\.)*)"'

HEADERS = {"en": "| # | Check | What is checked | Severity | Origin |", "fr": "| # | Contrôle | Ce qui est vérifié | Gravité | Origine |"}
SEVERITIES = {"ERROR": ("error", "erreur"), "WARNING": ("warning", "avertissement"), "INFO": ("info", "info")}
ORIGINS = {"VANILLA": "vanilla", "GDC": "GDC", "TILW": "TILW", "RL": "RL"}


def unescape(text):
    return text.replace('\\"', '"').replace("\\\\", "\\")


def read_catalogue():
    source = CATALOGUE.read_text(encoding="utf-8")
    titles_fr = re.search(r"GDC_EMMCheckLanguage\.FRENCH\)\s*return \{([^}]*)\}", source).group(1)
    titles_en = re.search(r"\n\t\treturn \{([^}]*)\};\n\t\}\n\n\t//-+\n\tstatic string GetBlockTitle", source).group(1)
    blocks = {"en": [unescape(t) for t in re.findall(STRING, titles_en)], "fr": [unescape(t) for t in re.findall(STRING, titles_fr)]}

    rules = []
    parts = re.split(r'\n\t\trule = Declare\(', source)[1:]
    for part in parts:
        head = re.match(r'"([\d.]+)", GDC_MMCheckOrigin\.(\w+), GDC_EMMCheckSeverity\.(\w+), GDC_EMMCheckFamily\.(\w+)\);', part)
        title = re.search(r"rule\.SetTitle\(" + STRING + r",\s*" + STRING + r"\);", part)
        description = re.search(r"rule\.SetDescription\(\s*" + STRING + r",\s*" + STRING + r"\);", part)
        sheet = re.search(r'rule\.m_sKB = "([^"]+)";', part)
        if not (head and title and description):
            raise SystemExit(f"error: rule {part[:20]!r} of the catalogue could not be read (Declare, SetTitle, SetDescription)")
        rules.append({
            "id": head.group(1), "origin": ORIGINS[head.group(2)], "severity": SEVERITIES[head.group(3)],
            "title": (unescape(title.group(1)), unescape(title.group(2))),
            "description": (unescape(description.group(1)), unescape(description.group(2))),
            "sheet": sheet.group(1) if sheet else None,
        })
    return blocks, rules


def table(language, blocks, rules):
    index = 0 if language == "en" else 1
    lines = [START]
    for number, block in enumerate(blocks[language], 1):
        block_rules = [r for r in rules if r["id"].split(".")[0] == str(number)]
        lines += ["", f"### {number}. {block}", ""]
        if not block_rules:
            lines.append("Coming soon." if language == "en" else "À venir.")
            continue

        lines += [HEADERS[language], "|---|---|---|---|---|"]
        for rule in block_rules:
            title = rule["title"][index]
            if rule["sheet"]:
                suffix = ".md" if language == "en" else ".fr.md"
                title = f"[{title}]({KB_LINK}{rule['sheet']}{suffix})"
            description = rule["description"][index].replace("|", "\\|")
            lines.append(f"| {rule['id']} | {title} | {description} | {rule['severity'][index]} | {rule['origin']} |")
    lines += ["", END]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="check only, write nothing")
    args = parser.parse_args()

    blocks, rules = read_catalogue()
    stale = []
    for language, guide in GUIDES.items():
        text = guide.read_text(encoding="utf-8")
        if START not in text or END not in text:
            print(f"error: {guide.name} has no RULES markers")
            return 1
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        updated = before + table(language, blocks, rules) + after
        if updated == text:
            continue
        stale.append(guide.name)
        if not args.check:
            guide.write_bytes(updated.encode("utf-8"))

    if args.check and stale:
        print(f"error: rule list out of date in {', '.join(stale)}: run rules_doc.py")
        return 1
    state = "up to date" if not stale else f"updated: {', '.join(stale)}"
    print(f"OK: {len(rules)} rules, user guides {state}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
